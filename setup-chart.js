let symbol="BTCUSDT",interval="4h",lastTime=0,lastBar=null,currentBars=[],volumeVisible=true;
let refreshTimer=0,canLive=false,markerView=null,priceLines=[],verifiedCount=0;
const el=id=>document.getElementById(id);
const fPrice=n=>{
 if(!Number.isFinite(Number(n)))return "—";
 const p=Number(n),digits=p<.1?7:p<1?5:p<100?4:2;
 return p.toLocaleString("tr-TR",{minimumFractionDigits:digits,maximumFractionDigits:digits});
};
const fPct=n=>Number.isFinite(n)?(n>=0?"+":"")+n.toFixed(2)+"%":"—";
const dateUTC=t=>new Date(Number(t)*1000).toLocaleString("tr-TR",{
 timeZone:"UTC",day:"2-digit",month:"2-digit",year:"numeric",hour:"2-digit",minute:"2-digit"});
