function rawToPoint(row){
 if(!Array.isArray(row)||row.length<7)return null;
 const time=Math.floor(Number(row[0])/1000),end=Number(row[6]);
 const open=Number(row[1]),high=Number(row[2]),low=Number(row[3]),
       close=Number(row[4]),volume=Number(row[5]);
 if(![time,end,open,high,low,close,volume].every(Number.isFinite) ||
    open<=0||close<=0||low<=0||high<Math.max(open,close)||low>Math.min(open,close))return null;
 return {time,open,high,low,close,volume:Math.max(0,volume),closed:end<Date.now()};
}
